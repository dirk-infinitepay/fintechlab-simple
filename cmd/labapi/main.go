// Labapi is the lab's one API: every lab-level call a person, a script, an
// agent or the console page makes goes here, at /v1 (docs/api/lab-api.md).
//
// It is a client of the simulated services and nothing more. Each route is
// the same HTTP call a human with curl would make against a service's own
// public surface, or the lab's own state (the merchant registry, the plugin
// registrations); so nothing in this lab can only be reached through it, and
// it being down must never be why a scenario cannot run. The harness does
// not know it exists.
//
// The console is a page served elsewhere (cmd/console) that calls this API
// like any other client. The console's old /api/* paths are served here too,
// as aliases, until every plugin registers at /v1 (docs/lab-api/plan.md,
// phase 4).
package main

import (
	"context"
	"crypto/subtle"
	"crypto/tls"
	"crypto/x509"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/webduvet/fintechlab-simple/internal/console"
	"github.com/webduvet/fintechlab-simple/internal/httputilx"
	"github.com/webduvet/fintechlab-simple/internal/waitfor"
)

type app struct {
	cat     *console.Catalogue
	mon     *console.Monitor
	reg     *console.Registry
	banks   *console.Banks
	prov    *console.Provisioner
	client  *http.Client
	secure  *http.Client
	bcCfg   string
	provErr string
	// keysDir is the lab's keys directory, read for the connect-your-
	// platform downloads.
	keysDir string
	// bcInternal is Banking Circle's internal bridge, where Worldline's
	// wire into the safeguarding accounts lands (Fund safeguarding
	// accounts on its card).
	bcInternal string
	// bc is the same Banking Circle client the Banks view uses, kept
	// directly so the Configuration view can ask the service what delivery
	// schedule it is *actually* running.
	bc *console.BankingCircleBank
	// token, when set, is the bearer every call but GET /health must carry
	// (LAB_API_TOKEN). Unset is the local default: no auth, so `make up`
	// stays one command.
	token string
}

func main() {
	addr := env("LISTEN", ":8097")

	plain := &http.Client{Timeout: 10 * time.Second}
	secure, tlsErr := tlsClient(
		env("CA_FILE", "keys/certs/ca.pem"),
		env("CLIENT_CERT", "keys/certs/client.pem"),
		env("CLIENT_KEY", "keys/certs/client-key.pem"),
	)
	if tlsErr != nil {
		// Not fatal. Without the CA the Banking Circle panels report why
		// they are empty, and the rest of the console still works --
		// a control panel that refuses to start because one peer's
		// credentials are missing is worse than one that says so.
		log.Printf("lab-api: no TLS client material (%v); banking-circle panels will show the error", tlsErr)
		secure = plain
	}

	cat := console.DefaultCatalogue()
	a := &app{
		cat:     cat,
		client:  plain,
		secure:  secure,
		bcCfg:   env("CONSOLE_BC_DELIVERY_CONFIG", "config/banking-circle.json"),
		keysDir: env("CONSOLE_KEYS_DIR", "keys"),
		token:   os.Getenv("LAB_API_TOKEN"),
		// The bridge, not the credentialed API: crediting a safeguarding
		// account stands in for a wire arriving, and the real bank has no
		// caller-facing route for that.
		bcInternal: env("CONSOLE_BC_INTERNAL_URL", "http://127.0.0.1:8095"),
	}
	a.mon = console.NewMonitor(cat, a.clientFor, envDuration("CONSOLE_PROBE_INTERVAL", 5*time.Second), 3*time.Second)

	reg, err := console.NewRegistry(env("CONSOLE_STATE_FILE", "console-data/registry.json"))
	if err != nil {
		log.Fatalf("lab-api: registry: %v", err)
	}
	a.reg = reg

	a.bc = &console.BankingCircleBank{
		BaseURL:  a.baseURL("banking-circle"),
		Client:   secure,
		User:     env("BC_USER", "sim"),
		Password: env("BC_PASSWORD", "sim-bc-dev-only"),
	}
	a.banks = console.NewBanks(
		&console.CoreLedgerBank{BaseURL: a.baseURL("bank"), Client: plain},
		a.bc,
	)

	// b4b writes its signing key on first start, concurrently with this one
	// on a fresh keys volume, and the provisioner reads it only here. A
	// short wait beats a console that says "disabled" until restarted.
	b4bKey := env("B4B_JWT_PRIVATE_KEY_PATH", "keys/b4b-keys/private.pem")
	_ = waitfor.Files(30*time.Second, b4bKey)
	prov, err := console.NewProvisioner(plain, reg,
		a.baseURL("b4b"),
		b4bKey,
		env("B4B_JWT_KEY_ID", "b4b-mock-1"),
		a.baseURL("worldline"),
	)
	a.prov = prov
	if err != nil {
		// Same reasoning as the TLS material: the key is generated by the
		// b4b service into a shared volume, so a console started first
		// simply has not seen it yet.
		a.provErr = err.Error()
		log.Printf("lab-api: %v (payout-rail provisioning disabled until the key is readable)", err)
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	go a.mon.Run(ctx)

	log.Printf("lab-api listening on %s (auth: %s)", addr, map[bool]string{true: "bearer token", false: "none"}[a.token != ""])
	log.Fatal(http.ListenAndServe(addr, logReq(a.routes())))
}

func (a *app) routes() http.Handler {
	// The API is the table in routes.go, so what GET /v1 lists is exactly
	// what is served, under its /v1 path and, until phase 4, its /api alias.
	mux := http.NewServeMux()
	table := a.apiRoutes()
	for _, rt := range table {
		h := rt.handler
		if h == nil {
			h = apiIndex(table)
		}
		for _, p := range rt.patterns() {
			mux.HandleFunc(p, h)
		}
	}
	return a.authorize(mux)
}

// authorize asks for LAB_API_TOKEN when one is set. GET /health stays open
// so a probe needs no secret, and so does nothing else.
func (a *app) authorize(next http.Handler) http.Handler {
	if a.token == "" {
		return next
	}
	want := []byte("Bearer " + a.token)
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method == http.MethodGet && r.URL.Path == "/health" {
			next.ServeHTTP(w, r)
			return
		}
		if subtle.ConstantTimeCompare([]byte(r.Header.Get("Authorization")), want) != 1 {
			w.Header().Set("WWW-Authenticate", `Bearer realm="lab-api"`)
			httputilx.Error(w, 401, "this lab API wants Authorization: Bearer $LAB_API_TOKEN")
			return
		}
		next.ServeHTTP(w, r)
	})
}

// clientFor picks the HTTP client for a service. Banking Circle's
// real-shaped listener wants a client certificate; nothing else does.
func (a *app) clientFor(s console.Service) *http.Client {
	if len(s.BaseURL) > 5 && s.BaseURL[:5] == "https" {
		return a.secure
	}
	return a.client
}

func (a *app) baseURL(id string) string {
	s, ok := a.cat.Get(id)
	if !ok {
		return ""
	}
	return s.BaseURL
}

// tlsClient trusts caFile and presents the client certificate when both
// halves are present -- Banking Circle's API requires mTLS by default.
func tlsClient(caFile, certFile, keyFile string) (*http.Client, error) {
	pem, err := os.ReadFile(caFile)
	if err != nil {
		return nil, err
	}
	pool := x509.NewCertPool()
	if !pool.AppendCertsFromPEM(pem) {
		return nil, os.ErrInvalid
	}
	cfg := &tls.Config{RootCAs: pool, MinVersion: tls.VersionTLS12}
	if cert, err := tls.LoadX509KeyPair(certFile, keyFile); err == nil {
		cfg.Certificates = []tls.Certificate{cert}
	}
	return &http.Client{
		Timeout:   10 * time.Second,
		Transport: &http.Transport{TLSClientConfig: cfg},
	}, nil
}

func env(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func envDuration(k string, def time.Duration) time.Duration {
	v := os.Getenv(k)
	if v == "" {
		return def
	}
	if d, err := time.ParseDuration(v); err == nil && d > 0 {
		return d
	}
	if n, err := strconv.Atoi(v); err == nil && n > 0 {
		return time.Duration(n) * time.Second
	}
	log.Printf("lab-api: %s=%q is not a duration; using %s", k, v, def)
	return def
}

func logReq(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		// Health probes every few seconds drown out the calls that matter.
		if strings.HasPrefix(r.URL.Path, "/v1") || strings.HasPrefix(r.URL.Path, "/api") {
			log.Printf("%s %s", r.Method, r.URL.Path)
		}
		next.ServeHTTP(w, r)
	})
}
